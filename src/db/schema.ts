/**
 * Server-side session records. The cookie carries a signed JWT whose payload
 * is `{ sid, sub, exp }`. The DB row is the source of truth: we can revoke
 * immediately on logout / password change / suspicious activity without
 * waiting for the JWT to expire. `token_hash` is sha-256 of the *JWT string*
 * so we can look up by cookie value without an extra index leak.
 */
export const authSessions = pgTable(
  "auth_sessions",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    tokenHash: text("token_hash").notNull(),
    userAgent: text("user_agent"),
    ipHash: text("ip_hash"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    lastSeenAt: timestamp("last_seen_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    revokedAt: timestamp("revoked_at", { withTimezone: true }),
  },
  (t) => ({
    tokenHashUnique: uniqueIndex("auth_sessions_token_hash_unique").on(
      t.tokenHash
    ),
    userIdx: index("auth_sessions_user_idx").on(t.userId),
  })
);

/**
 * Single-use magic-link tokens, sent by email. Used for two flows:
 *   1. Passwordless sign-in / sign-up.
 *   2. Email verification (after a password sign-up we can mail a link).
 * `token_hash` is sha-256 of the random token we mailed — never store the
 * raw token so a DB leak does not enable account takeover.
 */
export const magicLinkTokens = pgTable(
  "magic_link_tokens",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    email: varchar("email", { length: 254 }).notNull(),
    tokenHash: text("token_hash").notNull(),
    // 'signin' | 'verify_email'
    purpose: varchar("purpose", { length: 32 }).notNull(),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    consumedAt: timestamp("consumed_at", { withTimezone: true }),
  },
  (t) => ({
    tokenHashUnique: uniqueIndex("magic_link_tokens_token_hash_unique").on(
      t.tokenHash
    ),
    emailIdx: index("magic_link_tokens_email_idx").on(t.email),
  })
);

