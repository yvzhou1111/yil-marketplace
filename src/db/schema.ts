/**
 * Local shadow of a Stripe PaymentIntent.
 *
 * One row per Stripe PI. The `stripe_payment_intent_id` (pi_…) is the join
 * key the webhook handler uses to look us up. We never store card details;
 * Stripe is PCI-DSS Level 1 and we let them hold the PAN.
 *
 * State transitions are enforced by `src/payments/state.ts`; the DB also
 * has CHECK constraints + the payment_intents_refund_not_exceed invariant
 * as a last line of defense.
 *
 * Money columns are `bigint` minor units (cents for USD).
 */
export const paymentIntentState = pgEnum("payment_intent_state", [
  "pending",
  "authorized",
  "captured",
  "failed",
  "canceled",
  "refunded",
  "partially_refunded",
  "disputed",
]);

export const paymentIntents = pgTable(
  "payment_intents",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    orderId: uuid("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "restrict" }),
    stripePaymentIntentId: text("stripe_payment_intent_id").unique(),
    amountCents: bigint("amount_cents", { mode: "number" }).notNull(),
    currency: varchar("currency", { length: 3 }).notNull(),
    state: paymentIntentState("state").notNull().default("pending"),
    refundedAmountCents: bigint("refunded_amount_cents", { mode: "number" })
      .notNull()
      .default(0),
    lastErrorMessage: text("last_error_message"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => ({
    orderIdx: index("payment_intents_order_idx").on(t.orderId, t.createdAt),
    stateIdx: index("payment_intents_state_idx").on(t.state, t.createdAt),
    amountPositive: check(
      "payment_intents_amount_positive",
      sql`${t.amountCents} > 0`
    ),
    refundBounds: check(
      "payment_intents_refund_not_exceed",
      sql`${t.refundedAmountCents} <= ${t.amountCents}`
    ),
  })
);

