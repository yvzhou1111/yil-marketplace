export const listings = pgTable(
  "listings",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    sellerId: uuid("seller_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    title: varchar("title", { length: 140 }).notNull(),
    description: text("description").notNull().default(""),
    // Money — see header comment. Keep currency explicit so we can ship
    // multi-currency later without a destructive migration.
    amountCents: bigint("amount_cents", { mode: "number" }).notNull(),
    currency: varchar("currency", { length: 3 }).notNull().default("USD"),
    status: listingStatus("status").notNull().default("draft"),
    // Free-form inventory location; structured fields ship in a later issue.
    location: varchar("location", { length: 120 }).notNull().default(""),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
    // YIL-8 — Postgres full-text search vector. Generated from title (weight A)
    // and description (weight B). Maintained by Postgres; the app never writes
    // to it. Indexes are declared in the table builder below.
    searchVector: tsvector("search_vector"),
  },
  (t) => ({
    sellerIdx: index("listings_seller_idx").on(t.sellerId),
    // Hot browse path: live listings newest-first.
    activeByCreatedIdx: index("listings_active_by_created_idx")
      .on(t.createdAt.desc())
      .where(sql`${t.deletedAt} IS NULL`),
    activeByStatusIdx: index("listings_active_by_status_idx")
      .on(t.status, t.createdAt.desc())
      .where(sql`${t.deletedAt} IS NULL`),
    priceNonNegative: check(
      "listings_amount_cents_non_negative",
      sql`${t.amountCents} >= 0`
    ),
    // YIL-8 — GIN over the generated search_vector for FTS lookups.
    searchVectorGinIdx: index("listings_search_vector_gin_idx").using(
      "gin",
      t.searchVector
    ),
    // YIL-8 — trigram GIN on lower(title) for typo-tolerant prefix matching.
    titleTrgmGinIdx: index("listings_title_trgm_gin_idx").using(
      "gin",
      sql`lower(${t.title}) gin_trgm_ops`
    ),
  })
);

