/**
 * Orders drive the review lifecycle. A review can only be written once the
 * order has reached the `completed` state. Earlier states (initiated, paid,
 * fulfilled) intentionally disallow reviews so neither side can weaponize
 * them against the other before the deal is done. `disputed` also blocks
 * reviews; resolution is its own flow.
 *
 * State machine (canonical source: src/orders/state-machine.ts):
 *
 *   initiated ──► paid ──► fulfilled ──► completed
 *       │           │           │             │
 *       ▼           ▼           ▼             ▼
 *   cancelled   cancelled   disputed      disputed
 *                               │
 *                               ▼
 *                         completed | cancelled   (admin resolution)
 *
 * Every state transition is recorded in `order_state_transitions`. The DB
 * enforces legal (from_state, to_state) pairs via a CHECK constraint; the
 * app enforces which actor role may perform which transition. See ADR
 * 0002 for the rationale on splitting these two layers.
 */
export const orderState = pgEnum("order_state", [
  "initiated",
  "paid",
  "fulfilled",
  "completed",
  "disputed",
  "cancelled",
]);

/**
 * Who is recorded as having caused a transition. `system` covers automated
 * paths (Stripe webhooks, auto-confirm timers, settlement jobs); the actor
 * foreign key is nullable in that case. Buyers and sellers are the order's
 * own parties; admin covers operator actions from the admin console.
 */
export const orderTransitionActor = pgEnum("order_transition_actor", [
  "buyer",
  "seller",
  "admin",
  "system",
]);

export const orders = pgTable(
  "orders",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    listingId: uuid("listing_id")
      .notNull()
      .references(() => listings.id, { onDelete: "restrict" }),
    buyerId: uuid("buyer_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    sellerId: uuid("seller_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    state: orderState("state").notNull().default("initiated"),
    /**
     * Captured at order creation so later listing price changes don't
     * retroactively rewrite history. Kept in minor units (e.g. cents).
     */
    amountMinor: bigint("amount_minor", { mode: "number" }).notNull(),
    currency: varchar("currency", { length: 3 }).notNull().default("USD"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    // YIL-14 — state-specific audit timestamps. These mirror the *first* time
    // the order entered the named state and are denormalized on the orders
    // row so common operational queries ("average time to fulfilment")
    // don't have to walk the audit table. The audit table remains the
    // authoritative source for *who* and *why*.
    paidAt: timestamp("paid_at", { withTimezone: true }),
    fulfilledAt: timestamp("fulfilled_at", { withTimezone: true }),
    disputedAt: timestamp("disputed_at", { withTimezone: true }),
    cancelledAt: timestamp("cancelled_at", { withTimezone: true }),
  },
  (t) => ({
    sellerIdx: index("orders_seller_idx").on(t.sellerId, t.createdAt),
    buyerIdx: index("orders_buyer_idx").on(t.buyerId, t.createdAt),
    stateIdx: index("orders_state_idx").on(t.state, t.createdAt),
    /**
     * One active (non-cancelled) order per (buyer, listing) at a time.
     * Buyers can retry after cancelling — `cancelled` is excluded from
     * the partial unique index below.
     */
    activeByBuyer: uniqueIndex("orders_active_buyer_unique")
      .on(t.buyerId, t.listingId)
      .where(sql`${t.state} <> 'cancelled'`),
    amountNonNegative: check(
      "orders_amount_minor_non_negative",
      sql`${t.amountMinor} >= 0`
    ),
    /**
     * State-timestamp consistency: if the order is in the named state, the
     * matching timestamp must be set. The reverse (timestamp set but state
     * not yet advanced) is allowed so the trigger in migration 0003 can
     * update the timestamp before the state column in a single UPDATE.
     */
    paidConsistency: check(
      "orders_paid_at_consistency",
      sql`(${t.state} IN ('paid','fulfilled','completed','disputed'))
          OR ${t.paidAt} IS NULL`
    ),
    fulfilledConsistency: check(
      "orders_fulfilled_at_consistency",
      sql`(${t.state} IN ('fulfilled','completed','disputed'))
          OR ${t.fulfilledAt} IS NULL`
    ),
    completedConsistency: check(
      "orders_completed_at_consistency",
      sql`(${t.state} = 'completed')
          OR ${t.completedAt} IS NULL`
    ),
    disputedConsistency: check(
      "orders_disputed_at_consistency",
      sql`(${t.state} = 'disputed')
          OR ${t.disputedAt} IS NULL`
    ),
    cancelledConsistency: check(
      "orders_cancelled_at_consistency",
      sql`(${t.state} = 'cancelled')
          OR ${t.cancelledAt} IS NULL`
    ),
  })
);

/**
 * YIL-14 — Append-only audit log of every state transition on an order.
 *
 * One row is written for each successful transition. The application
 * computes `from_state` and `to_state`, then INSERTs. A CHECK constraint
 * rejects any (from_state, to_state) pair that is not in the allowed set,
 * which gives us a defense-in-depth guarantee even if the application layer
 * is bypassed (e.g. by a raw SQL maintenance script).
 *
 * `actor_user_id` is nullable because `system` transitions (Stripe webhook
 * marking an order paid, auto-confirm timer marking an order completed)
 * have no human actor. `actor_role` is always present and tells you what
 * *kind* of actor was responsible.
 *
 * `metadata` is intentionally jsonb and opaque to the schema: each
 * transition can carry whatever context it needs (Stripe PaymentIntent id,
 * tracking number, dispute evidence url, admin note). The application
 * documents the expected shape per transition in src/orders/state-machine.ts.
 *
 * No updated_at — audit rows are immutable. No deleted_at — we never
 * erase history. If a row was inserted in error, write a counter-row.
 */
export const orderStateTransitions = pgTable(
  "order_state_transitions",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    orderId: uuid("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "restrict" }),
    // null on the very first row for an order (the order row itself is
    // created in 'initiated' state; no transition row precedes it).
    fromState: orderState("from_state"),
    toState: orderState("to_state").notNull(),
    actorUserId: uuid("actor_user_id").references(() => users.id, {
      onDelete: "restrict",
    }),
    actorRole: orderTransitionActor("actor_role").notNull(),
    // Free-form, human-readable. Truncated to 500 chars at the DB layer to
    // keep the audit table light; longer narratives go in `metadata`.
    reason: varchar("reason", { length: 500 }).notNull().default(""),
    // Transition-specific structured context. Examples:
    //   paid       → { stripe_payment_intent_id, stripe_charge_id }
    //   fulfilled  → { carrier, tracking_number }
    //   disputed   → { opened_by, evidence_url }
    //   completed  → { via: "buyer_confirm" | "auto_confirm" | "admin_resolve" }
    metadata: jsonb("metadata").notNull().default(sql`'{}'::jsonb`),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => ({
    /**
     * Hot read path: "show me the history of order X". Sort by created_at
     * so the natural ordering of the audit log matches insertion order.
     */
    orderHistoryIdx: index("order_state_transitions_order_history_idx").on(
      t.orderId,
      t.createdAt
    ),
    /**
     * Operational: "show me everything buyer U did to orders".
     */
    actorIdx: index("order_state_transitions_actor_idx").on(
      t.actorUserId,
      t.createdAt
    ),
    /**
     * Operational: "show me all open disputes opened in the last 24h".
     */
    toStateIdx: index("order_state_transitions_to_state_idx").on(
      t.toState,
      t.createdAt
    ),
    /**
     * Defense-in-depth: the (from_state, to_state) pair must be a legal
     * transition. The canonical allow-list lives in
     * src/orders/state-machine.ts and is mirrored here so the database
     * itself can reject illegal rows.
     */
    legalTransition: check(
      "orders_status_transition_allowed",
      sql`(${t.fromState}, ${t.toState}) IN (
        ('initiated',  'paid'),
        ('initiated',  'cancelled'),
        ('paid',       'fulfilled'),
        ('paid',       'disputed'),
        ('paid',       'cancelled'),
        ('fulfilled',  'completed'),
        ('fulfilled',  'disputed'),
        ('completed',  'disputed'),
        ('disputed',   'completed'),
        ('disputed',   'cancelled')
      )`
    ),
    /**
     * Actor consistency: `system` is the only role that may have a NULL
     * actor_user_id. Every buyer/seller/admin row must point at a real
     * user. (The FK enforces existence when present.)
     */
    actorRoleConsistency: check(
      "orders_transition_actor_consistency",
      sql`(${t.actorRole} = 'system') = (${t.actorUserId} IS NULL)`
    ),
  })
);

/**
 * Who is writing the review, from the order's POV.
 *  - `buyer`  = the buyer writing about the seller
 *  - `seller` = the seller writing about the buyer
 *
 * Two-sided means exactly one of each per completed order, written by the
 * party themselves. We never let one side impersonate the other, and we
 * never auto-fill a review.
 */
export const reviewRole = pgEnum("review_role", ["buyer", "seller"]);

export const reviews = pgTable(
  "reviews",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    orderId: uuid("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "cascade" }),
    reviewerId: uuid("reviewer_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    revieweeId: uuid("reviewee_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    role: reviewRole("role").notNull(),
    /** 1..5 inclusive. Enforced by a check constraint below. */
    rating: integer("rating").notNull(),
    body: text("body").notNull().default(""),
    /** Soft-hide when a moderator removes the review for abuse. */
    hiddenAt: timestamp("hidden_at", { withTimezone: true }),
    hiddenReason: text("hidden_reason"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => ({
    /**
     * One review per (order, role). The buyer writes one review for the
     * seller, and the seller writes one review for the buyer.
     */
    onePerSide: uniqueIndex("reviews_one_per_side_unique").on(t.orderId, t.role),
    revieweeIdx: index("reviews_reviewee_idx").on(t.revieweeId, t.createdAt),
    reviewerIdx: index("reviews_reviewer_idx").on(t.reviewerId, t.createdAt),
    orderIdx: index("reviews_order_idx").on(t.orderId),
    /** DB-level guard: ratings must be 1..5. */
    ratingRange: check(
      "reviews_rating_range",
      sql`${t.rating} between 1 and 5`
    ),
  })
);

/**
 * User-driven abuse reports. Multiple users can flag the same review; the
 * system counts flags and escalates once a threshold is hit. Moderators act
 * via the separate `review_moderation_actions` audit table — we keep
 * *reports* and *decisions* in distinct tables so the audit trail is honest.
 */
export const reviewFlagReason = pgEnum("review_flag_reason", [
  "spam",
  "harassment",
  "hate",
  "threat",
  "doxxing",
  "off_topic",
  "other",
]);

export const reviewFlags = pgTable(
  "review_flags",
  {
    id: uuid("id").primaryKey().default(sql`gen_random_uuid()`),
    reviewId: uuid("review_id")
      .notNull()
      .references(() => reviews.id, { onDelete: "cascade" }),
    reporterId: uuid("reporter_id")
      .notNull()
      .references(() => users.id, { onDelete: "restrict" }),
    reason: reviewFlagReason("reason").notNull(),
    notes: text("notes").notNull().default(""),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    resolvedAt: timestamp("resolved_at", { withTimezone: true }),
    resolution: text("resolution"),
  },
  (t) => ({
    /** One reporter can flag the same review once; duplicates are merged. */
    onePerReporter: uniqueIndex("review_flags_one_per_reporter").on(
      t.reviewId,
      t.reporterId
    ),
    /** Common read path: all open flags on a given review. */
    openByReview: index("review_flags_open_by_review_idx")
      .on(t.reviewId)
      .where(sql`${t.resolvedAt} IS NULL`),
  })
);

