/**
 * Core data model for the YIL marketplace.
 *
 * Tables:
 *   users                    — buyers and sellers (auth fields are owned by
 *                              YIL-4; we only carry the public profile here).
 *   auth_sessions            — server-side session store, indexed by JWT hash
 *                              (YIL-4).
 *   magic_link_tokens        — single-use tokens for passwordless auth and
 *                              email verification (YIL-4).
 *   categories               — flat taxonomy, slug-addressable, parent_id is
 *                              optional so we can build a tree later without a
 *                              migration.
 *   listings                 — items offered for sale by a seller.
 *   images                   — photos attached to a single listing, ordered.
 *   listing_categories       — many-to-many join between listings and
 *                              categories.
 *   orders                   — buyer–seller transactions on a listing (YIL-14).
 *   order_state_transitions  — append-only audit log of every status change
 *                              (YIL-14). One row per transition, with
 *                              actor identity, role, reason, and arbitrary
 *                              metadata (Stripe intent ids, tracking numbers,
 *                              dispute reasons, etc.).
 *   reviews                  — two-sided reviews on completed orders (YIL-10).
 *   review_flags             — user-driven abuse reports on reviews (YIL-10).
 *   review_moderation_actions — moderator decision audit trail (YIL-10).
 *
 * Conventions:
 *   - Primary keys are UUIDv4 generated by Postgres (`gen_random_uuid()`),
 *     not application-assigned. Keeps the API client-agnostic and avoids
 *     sequential-id enumeration leaks.
 *   - Every table has `created_at` / `updated_at`. `updated_at` is bumped by a
 *     trigger on UPDATE (see migration 0000).
 *   - User-generated content (`users`, `listings`, `images`, `orders`) is
 *     soft-deleted with `deleted_at`; `categories`,
 *     `order_state_transitions`, and `review_moderation_actions` are
 *     append-only history rows.
 *   - All FKs use `ON DELETE RESTRICT` to surface dangling-reference bugs as
 *     errors rather than silently losing history. Cascades are explicit on
 *     `images.listing_id` and `reviews.order_id` because a deleted listing
 *     should not retain orphan image rows, and reviews only exist on
 *     orders.
 *   - Money is stored as `amount_cents bigint` + `currency char(3)`. Never
 *     use floats for prices.
 *   - All timestamps are `timestamptz` in UTC.
 *
 * Order state machine (YIL-14):
 *   See docs/architecture/transactions.md and
 *   docs/adr/0003-order-state-machine.md. The `order_state` enum is the
 *   single source of truth for legal states; the
 *   `orders_status_transition_allowed` CHECK constraint on
 *   `order_state_transitions` enforces legal (from_state, to_state) pairs in
 *   the database, and `src/orders/state-machine.ts` enforces both legal
 *   transitions and actor-role permissions in application code with
 *   structured guard failures.
 */
